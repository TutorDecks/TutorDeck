function allowed(f) {
  if (f.type === "toggle") return "Yes / No";
  if (f.type === "note") return "(a note, nothing to choose)";
  if (f.options) return f.options.map(function (o) {
    const so = (f.soonOptions || []).indexOf(o[0]) >= 0;
    const label = String(o[1]).split(" — ")[0];
    return "`" + String(o[0]) + "` " + label + (so ? " **[SOON]**" : "");
  }).join("<br>");
  return { text: "any text", email: "an email address", color: "`#RRGGBB`", number: "whole number ≥ 0", days: "whole number ≥ 0 (days)",
           money: "whole cents ≥ 0", percent: "whole basis points ≥ 0 (100 = 1%)", list: "numbers separated by commas" }[f.type] || f.type;
}
function dflt(v, f) {
  if (v === undefined) return "—";
  if (f.type === "toggle") return v ? "Yes" : "No";
  if (Array.isArray(v)) return v.join(", ");
  return v === "" ? "(empty)" : "`" + String(v) + "`";
}

function build() {
  const dc = S.defaults("centre"), ds = S.defaults("solo"), out = [];
  const seen = [];
  S.STEPS.forEach(function (st) {
    out.push("#### Step " + st.n + " — " + st.title + "\n");
    if (!st.fields.length) { out.push(stepNote(st) + "\n"); return; }
    out.push("| Setting (`path`) | Plain meaning | Allowed values | Default (centre) | Status and notes |\n|---|---|---|---|---|");
    st.fields.forEach(function (f) {
      seen.push(f.path);
      const n = N[f.path];
      if (!n) throw new Error("No note written for " + f.path + " — add it to docs/product/build-options.js");
      const key = f.soon ? "SOON" : n[1];
      const tag = n[1] === "BRANCH" ? "**[BRANCH]** `claude/t3-4-charges`, otherwise " + T.SAVED : (T[key] || n[1]);
      const soonOpts = (f.soonOptions && f.soonOptions.length) ? " Choices marked [SOON] cannot be picked yet." : "";
      const label = f.label ? f.label : "(note)";
      out.push("| " + label + " (`" + f.path + "`) | " + n[0] + " | " + allowed(f) + " | " + dflt(S.get(dc, f.path), f) + " | " + tag + (n[2] ? " " + n[2] : "") + soonOpts + " |");
    });
    out.push("");
  });
  // the solo preset
  out.push("#### The `solo` preset\n");
  out.push("A solo tutor is an organisation of one created with preset `solo`: the same settings, defaults changed where a one-person business differs. A solo tutor never sees this wizard; the preset only fills the stored defaults.\n");
  const diffs = [];
  S.STEPS.forEach(function (st) { st.fields.forEach(function (f) {
    const a = JSON.stringify(S.get(dc, f.path)), b = JSON.stringify(S.get(ds, f.path));
    if (a !== b) diffs.push("| `" + f.path + "` | " + dflt(S.get(dc, f.path), f) + " | " + dflt(S.get(ds, f.path), f) + " |");
  }); });
  out.push("| Setting | Centre default | `solo` default |\n|---|---|---|");
  out.push.apply(out, diffs); out.push("");
  out.push("Also stored for every organisation: `schema_version` = " + S.SCHEMA_VERSION + ", `preset`, and an empty `data` section (reserved for imported data, step 9).\n");
  return { text: out.join("\n"), paths: seen };
}
function stepNote(st) {
  return ({
    calendar: "",
    users: "People are invited here, not saved as settings. See 2.4: invite, permissions, switch off. The permission catalogue (`" + S.STAFF_PERMISSIONS.map(function (p) { return p.key; }).join("`, `") + "`) is in 2.3.",
    import: "**[SOON]** CSV import: templates for tutors, students (level, subjects, class, fee plan), parents and households. Nothing to choose yet.",
    review: "A read-only summary of every step with 'Edit' links, a sample invoice and a sample pay statement, then **Launch**."
  })[st.id] || "";
}

function pathsInSchema() { const p = []; S.STEPS.forEach(function (st) { st.fields.forEach(function (f) { p.push(f.path); }); }); return p; }

const arg = process.argv[2] || "";
if (arg === "--check") {
  const md = fs.readFileSync(GUIDE, "utf8"), all = pathsInSchema(), miss = all.filter(function (p) { return md.indexOf("`" + p + "`") < 0; });
  console.log("Settings in org-settings.js: " + all.length + " (including " + S.STEPS.reduce(function (n, st) { return n + st.fields.filter(function (f) { return f.type === "note"; }).length; }, 0) + " notes)");
  console.log("Missing from the guide: " + miss.length);
  miss.forEach(function (p) { console.log("  MISSING " + p); });
  // staff permissions must all be explained too
  const pm = S.STAFF_PERMISSIONS.map(function (p) { return p.key; }).filter(function (k) { return md.indexOf("`" + k + "`") < 0; });
  console.log("Staff permissions missing: " + pm.length); pm.forEach(function (k) { console.log("  MISSING " + k); });
  process.exit(miss.length || pm.length ? 1 : 0);
} else {
  const b = build();
  if (arg === "--write") {
    let md = fs.readFileSync(GUIDE, "utf8");
    const i = md.indexOf(START), j = md.indexOf(END);
    if (i < 0 || j < 0) throw new Error("OPTIONS markers not found in the guide");
    md = md.slice(0, i + START.length) + "\n\n" + b.text + "\n" + md.slice(j);
    fs.writeFileSync(GUIDE, md);
    console.log("Wrote " + b.paths.length + " settings into " + path.relative(process.cwd(), GUIDE));
  } else console.log(b.text);
}
