#!/usr/bin/env python3
"""Builds docs/orchestrator/dev-apply-pack-b8.sql: the ONE migration bundle 8 adds (db/migration_b8_fix.sql) wrapped in a read-only pre-check,
a safety stop and a read-only post-check. DEV already has everything up to and including bundle 7's pack (docs/orchestrator/dev-apply-pack.sql).

    python3 tools/build-dev-pack-b8.py            # writes the file
    python3 tools/build-dev-pack-b8.py --check    # exits 1 if the file on disk is out of date
"""
import os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "docs/orchestrator/dev-apply-pack-b8.sql")
FUNCS = ["credit_consider", "centre_deposit_run_candidates", "centre_deposit_status"]
B7 = [("bundle 7: org_export (org_export_catalog)", "to_regprocedure('public.org_export_catalog()') is not null"),
      ("bundle 7: tutor_own_pay (tutor_my_pay)", "to_regprocedure('public.tutor_my_pay(date,date)') is not null"),
      ("bundle 7: tutor_link_propose (schedule_requests)", "to_regclass('public.schedule_requests') is not null"),
      ("bundle 6: makeup_credits (credit_consider)", "exists (select 1 from pg_proc where pronamespace='public'::regnamespace and proname='credit_consider')"),
      ("bundle 5: centre_deposits (centre_deposit_status)", "exists (select 1 from pg_proc where pronamespace='public'::regnamespace and proname='centre_deposit_status')")]
def has(f): return "exists (select 1 from pg_proc where pronamespace='public'::regnamespace and proname='%s' and prosrc like '%%B8-FIX%%')" % f

def main():
    mig = open(os.path.join(ROOT, "db/migration_b8_fix.sql")).read().rstrip("\n") + "\n"
    allok = "\n    and ".join("(" + c + ")" for _, c in B7)
    rows = ",\n".join("  ('%s', %s)" % (l, c) for l, c in B7)
    o = []
    w = o.append
    w("""-- =====================================================================================================
-- TutorDeck — DEV APPLY PACK, test bundle 8 (task T53).   PASTE INTO THE SUPABASE SQL EDITOR OF THE **DEV** PROJECT ONLY (tuzxsqkfzrjssnpcoale).
-- NEVER run on LIVE (rnjvswkejbrhbaytutai). (On LIVE the safety stop below also refuses: LIVE has no organisation tables yet.)
-- GENERATED by tools/build-dev-pack-b8.py: do not edit by hand; re-run the script.
-- =====================================================================================================
-- ONE part, db/migration_b8_fix.sql (undo: db/migration_b8_fix_down.sql). It REPLACES three functions and creates no table, column or policy:
--   credit_consider                  (F6: a trial lesson never earns a make-up credit)
--   centre_deposit_run_candidates    (F4: a discarded deposit draft is raised again)
--   centre_deposit_status            (F4/F5: 'discarded', 'refunded' and 'settled' states; a refunded deposit is not "to collect")
-- Needs on DEV first: bundle 7's pack (docs/orchestrator/dev-apply-pack.sql). Safe to run twice. Changes no row of data.
-- The result you see is the LAST query (the post-check).
-- =====================================================================================================
""")
    w("-- ####################################### PRE-CHECK (read-only) #######################################")
    w("""select 'PRE-CHECK' as step, m.migration, case when m.ok then 'present' else 'MISSING' end as state
from (values
%s
) as m(migration, ok)
union all
select 'PRE-CHECK', 'b8_fix already applied?', case when %s then 'yes (re-running is harmless)' else 'no (this pack applies it)' end
union all
select 'PRE-CHECK', 'OVERALL', case when
    %s
  then 'ready' else 'NOT READY - apply bundle 7''s pack first' end;
""" % (rows, " and ".join(has(f) for f in FUNCS), allok))
    w("""do $$
begin
  if to_regclass('public.organisations') is null or to_regclass('public.memberships') is null then
    raise exception 'STOP: this database has no organisation tables. The pack is for the DEV project only, after bundle 7''s pack.';
  end if;
  if not (%s) then
    raise exception 'STOP: bundle 7 is not (fully) on this database. Apply its pack first (see the PRE-CHECK MISSING lines).';
  end if;
end $$;
""" % allok)
    w("-- #####################################################################################################\n-- ### PART 1 of 1 — follow-up fixes F4, F5, F6\n-- ### file: db/migration_b8_fix.sql   undo: db/migration_b8_fix_down.sql\n-- #####################################################################################################")
    w(mig)
    w("-- ####################################### POST-CHECK (read-only; this is the result you see) #######################################")
    w("""select 'POST-CHECK' as step, f.n as item, case when %s then 'present' else 'MISSING' end as state
from (values %s) f(n)
union all
select 'POST-CHECK', 'OVERALL', case when %s then 'OK - all 3 functions carry the B8-FIX rules' else 'NOT OK - see the MISSING lines above' end
order by 1, 3 desc, 2;""" % ("exists (select 1 from pg_proc p where p.pronamespace='public'::regnamespace and p.proname=f.n and p.prosrc like '%B8-FIX%')",
        ",".join("('%s')" % f for f in FUNCS), " and ".join(has(f) for f in FUNCS)))
    return "\n".join(o) + "\n"

if __name__ == "__main__":
    text = main()
    if "--check" in sys.argv:
        sys.exit(0 if os.path.exists(OUT) and open(OUT).read() == text else 1)
    open(OUT, "w").write(text); print("wrote", OUT, len(text.splitlines()), "lines")
